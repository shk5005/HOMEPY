const ROLE_ANALYST =
`[R - Role · 역할]
당신은 20년 경력의 CFA 애널리스트입니다.
모닝스타, 메리츠, NH 출신 시니어급으로 글로벌 시장 분석을 1,000건 이상 수행했습니다.
당신은 낙관 편향 없이, 데이터와 출처로만 말합니다.`;

/** 할루시네이션 방지 5대 룰 블록 — 모든 프롬프트에 강제 부착 */
export function guardBlock() {
  return `[필수 규칙 · 할루시네이션 차단]\n` +
    GUARD_RULES.map((r, i) => `${i + 1}. ${r}`).join('\n');
}

/** 실시간 시세 앵커 — AI의 과거 학습값 사용을 원천 차단 */
export function priceAnchor(quotes, asOf) {
  if (!quotes?.length) {
    return `[시세 앵커]
⚠️ 반드시 오늘 기준 최신 데이터를 웹 검색으로 조회하세요.
학습된 과거 데이터 사용 금지. 실시간 주가·뉴스·공시 정보를 검색해서 쓰세요.`;
  }
  const lines = quotes.map(q => {
    const bits = [`현재가: ${won(q.price)}`];
    if (q.change != null) bits.push(`(${q.change >= 0 ? '+' : ''}${q.change.toLocaleString('ko-KR')}원)`);
    if (q.per  != null) bits.push(`PER ${q.per}`);
    if (q.pbr  != null) bits.push(`PBR ${q.pbr}`);
    if (q.cap  != null) bits.push(`시총 ${q.cap}`);
    if (q.band) bits.push(`52주 ${q.band}`);
    return `• ${q.name}: ${bits.join(' · ')}`;
  }).join('\n');
  return `[시세 앵커 — ${asOf} 기준 실시간 조회값]
${lines}

⚠️ 위 가격을 분석의 기준점으로 사용하세요. AI 추측·과거 학습값으로 대체 금지.
⚠️ 위에 없는 수치는 반드시 오늘 기준 웹 검색으로 확인 후 출처 URL을 첨부하세요.`;
}

const compose = (...blocks) => blocks.filter(Boolean).join('\n\n') + '\n\n' + guardBlock();

/* ---------- 1. 종목 발굴 (RICE) ---------- */
export function discoveryPrompt(cfg) {
  const style = STYLES.find(s => s.id === cfg.style) || STYLES[0];
  const sectors = cfg.sectors?.length ? cfg.sectors.join(', ') : '전 섹터';
  const excl = (cfg.exclusions || []).filter(Boolean);

  return compose(
    ROLE_ANALYST,
    `[I - Instruction · 지시사항]
다음 조건에 맞는 종목 ${cfg.count}개를 발굴해 주세요.

스크리닝 조건:
- 섹터: ${sectors}
- 투자 스타일: ${style.label}
- 스크리닝 필터: ${cfg.filter || style.filter}
- 중점 분석: ${cfg.focus || '시장점유율 확대, 신사업 진출'}
- 투자 기간: ${cfg.horizon}
- 목표 수익률: ${cfg.target}% 이상

제외 조건:
${excl.length ? excl.map(e => `- ${e}`).join('\n') : '- 최근 2년 연속 적자 기업\n- 감사의견 비적정 기업\n- 시가총액 1,000억 미만'}`,
    `[C - Context · 맥락]
- 대상 시장: ${cfg.market || '한국 코스피 200'}
- 보유 기간: ${cfg.horizon}
- 투자자 위험 성향: ${cfg.risk || '중위험'}
- 현재 시장 상황과 해당 산업 업황을 고려하여 분석할 것
- 글로벌 경쟁사 대비 국내 기업의 경쟁력을 평가할 것
- 단기 모멘텀보다 6개월 이상 관점의 구조적 성장을 중시할 것`,
    `[E - Example · 출력 형식]
결과는 반드시 아래 표 형식으로 작성해 주세요.

| 순위 | 종목 | 현재가 | 매수가 | 목표가 | 손절가 | 추천 근거 | 출처 URL |
|------|------|--------|--------|--------|--------|-----------|----------|
| 1 | ... | ... | ... | ... | ... | ... | ... |

표 아래에 각 종목별로 '탈락시킨 경쟁 종목 1개와 그 이유'를 한 줄씩 덧붙여 주세요.`,
    priceAnchor(null)
  );
}

/* ---------- 2. 교차검증 종합 비교 ---------- */
export function crossCheckPrompt(panels, consensus) {
  const dump = panels
    .filter(p => p.text?.trim())
    .map(p => `───── ${p.label} 답변 ─────\n${p.text.trim()}`)
    .join('\n\n');
  const names = consensus.map(c => c.name).join(', ') || '(합의 종목 없음)';

  return compose(
    ROLE_ANALYST,
    `[I - Instruction · 지시사항]
아래는 서로 다른 3개 AI가 동일한 스크리닝 조건에 대해 내놓은 종목 추천 결과입니다.
당신의 역할은 새 종목을 추가하는 것이 아니라, 이 3개 답변을 **교차 검증**하는 것입니다.

1. 3개 AI가 공통으로 추천한 종목과, 1곳에서만 나온 종목을 분리하세요.
2. 공통 추천 종목이 왜 공통으로 뽑혔는지, 근거가 서로 일치하는지 검증하세요.
3. **근거가 서로 충돌하는 지점**을 반드시 찾아내 명시하세요. (예: A는 수주 확대, B는 수주 둔화)
4. 1곳에서만 나온 종목 중 '나머지 2곳이 왜 빠뜨렸는지' 추정 이유를 쓰세요.
5. 세 답변 모두에서 출처 URL이 없는 수치는 '확인 불가'로 표기하고, 그 수치에 의존한 추천은 신뢰도를 낮추세요.`,
    `[C - Context · 맥락]
- 지니 앱이 자동 추출한 합의 종목(2곳 이상 언급): ${names}
- 하나의 AI만 믿는 것은 투자자가 빠지는 대표적 함정입니다. 다수결이 아니라 **근거의 질**로 판단하세요.
- 3개 AI가 모두 같은 실수를 했을 가능성(공통 학습 데이터 편향)도 함께 점검하세요.`,
    `[E - Example · 출력 형식]

■ 1) 합의 종목 매트릭스
| 종목 | ChatGPT | Claude | Perplexity | 합의 수준 | 근거 일치 여부 |

■ 2) 근거 충돌 지점
| 종목 | 쟁점 | A 주장 | B 주장 | 어느 쪽이 검증 가능한가 | 출처 |

■ 3) 단독 추천 종목 검토
| 종목 | 추천 AI | 단독 추천 이유 | 나머지가 빠뜨린 추정 이유 | 채택/기각 |

■ 4) 최종 공통 3종목 + 채택 사유 (출처 URL 필수)

${dump ? `\n[검증 대상 원문]\n${dump}` : ''}`
  );
}

